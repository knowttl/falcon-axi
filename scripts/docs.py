#!/usr/bin/env python3
"""Generate public command documentation, or check it without writing."""

import argparse
from pathlib import Path

from falcon_axi.commands import COMMAND_SPECS
from falcon_axi.scopes import scope_rows

REPO = Path(__file__).resolve().parent.parent
START = "<!-- commands:start -->"
END = "<!-- commands:end -->"


def command_table() -> str:
    rows = ["| Command | Purpose |", "| --- | --- |"]
    for spec in COMMAND_SPECS.values():
        description = spec.summary.strip().removeprefix(spec.name).strip().replace("|", "\\|")
        rows.append(f"| `{spec.name}` | {description} |")
    return "\n".join(rows)


def reference() -> str:
    lines = [
        "# Command reference",
        "",
        "Generated by `uv run scripts/docs.py` from the command and permission registries.",
        "Run `falcon-axi --help` for global flags; run a command with `--help` for its reference.",
        "Run `falcon-axi` without arguments for recent detections and severity counts.",
        "",
        "## API client permissions",
        "",
        "Grant only the scopes needed for the commands you use and the policy or exclusion type you select.",
        "Product licensing also controls availability.",
        "",
        "| Scope | Commands | Requirement |",
        "| --- | --- | --- |",
    ]
    for row in scope_rows():
        lines.append(f"| `{row['scope']}` | {row['commands']} | {row['required']} |")
    for spec in COMMAND_SPECS.values():
        lines.extend(["", f"## {spec.name}", "", "```text", spec.help, "```"])
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail on stale documentation without writing")
    args = parser.parse_args(argv)
    readme = REPO / "README.md"
    before, rest = readme.read_text(encoding="utf-8").split(START)
    _, after = rest.split(END)
    expected = {
        readme: f"{before}{START}\n{command_table()}\n{END}{after}",
        REPO / "docs/commands.md": reference(),
    }
    stale = [path for path, content in expected.items() if not path.exists() or path.read_text(encoding="utf-8") != content]
    if args.check:
        if stale:
            print("command documentation is stale; run `uv run scripts/docs.py`")
            return 1
        print("command documentation is current")
    else:
        for path in stale:
            path.write_text(expected[path], encoding="utf-8")
        print("wrote command documentation")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
