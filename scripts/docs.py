#!/usr/bin/env python3
"""Generate public command documentation, or check it without writing."""

import argparse
import re
from pathlib import Path

from falcon_axi.commands import COMMAND_SPECS
from falcon_axi.scopes import scope_rows

REPO = Path(__file__).resolve().parent.parent
START = "<!-- commands:start -->"
END = "<!-- commands:end -->"
SCOPE_START = "<!-- permissions:start -->"
SCOPE_END = "<!-- permissions:end -->"


def command_table() -> str:
    rows = ["| Command | Purpose |", "| --- | --- |"]
    for spec in COMMAND_SPECS.values():
        description = spec.summary.strip().removeprefix(spec.name).strip()
        argument = re.match(r"(<[^>]+>)\s+", description)
        command = spec.name
        if argument:
            command += f" {argument[1]}"
            description = description[argument.end() :]
        description = description.replace(" (N4)", "").replace("|", "\\|")
        rows.append(f"| `{command}` | {description} |")
    return "\n".join(rows)


def permission_table() -> str:
    rows = ["| Scope | Commands | Requirement |", "| --- | --- | --- |"]
    for row in scope_rows():
        rows.append(f"| `{row['scope']}` | {row['commands']} | {row['required']} |")
    return "\n".join(rows)


def reference() -> str:
    lines = [
        "# Command reference",
        "",
        "[Commands](#commands) • [API client permissions](#api-client-permissions) • "
        "[Pagination and walks](#pagination-and-walks) • [Per-command help](#detection-summary)",
        "",
        "Generated by `uv run scripts/docs.py` from the command and permission registries.",
        "Run `falcon-axi --help` for global flags; run a command with `--help` for its reference.",
        "Run `falcon-axi` without arguments for recent detections and severity counts.",
        "",
        "## Commands",
        "",
        "This generated table is the authoritative list of shipped commands.",
        "Names omit the `falcon-axi` prefix; positional arguments stay inside code spans.",
        "",
        START,
        command_table(),
        END,
        "",
        "## API client permissions",
        "",
        "Create a client under **Support and resources > API clients and keys** in Falcon.",
        "Grant only the scopes needed for the commands you use and the policy or exclusion type you select.",
        "Product licensing also controls availability.",
        "Missing permissions produce `SCOPE_DENIED`; leaving unused scopes ungranted is supported.",
        "Run `falcon-axi scopes` to inspect the matrix offline.",
        "",
        SCOPE_START,
        permission_table(),
        SCOPE_END,
        "",
        "## Pagination and walks",
        "",
        "One invocation reads one page by default.",
        "Use `--limit N` where supported, then pass the emitted `continuation_cursor` as `--cursor <token>`.",
        "Preserve the query and credential context; cursors cannot move between queries or tenants.",
        "",
        "Detection, host, account, and vulnerability lists support `--all --max-rows N` with a default cap of 1000.",
        "An incomplete walk keeps its rows, exits successfully, and prints `partial: true` with a `stop_reason`.",
        "Detection walks stop at 10000 query rows; host walks stop at 9999.",
        "Narrow the filter at these boundaries; a cursor is emitted only if the next page is reachable.",
        "Run the selected list with `--help` for its limits.",
        "",
        "NG-SIEM jobs have no `--cursor` or `--limit` flags.",
        "Bound results in CQL, for example with `head(200)`, then poll with `search status <id>`.",
        "Cancel unfinished jobs with `search stop <id>`.",
        "For validation failures and HTTP 400 rejections, follow the diagnostic fix hints.",
        "Review completed-job warnings and `parsed_query` before relying on results.",
        "`search start --wait` advises when the normalized filter differs from the submitted query.",
    ]
    for spec in COMMAND_SPECS.values():
        lines.extend(["", f"## {spec.name}", "", "```text", spec.help, "```"])
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail on stale documentation without writing")
    args = parser.parse_args(argv)
    expected = {
        REPO / "docs/commands.md": reference(),
    }
    stale = [path for path, content in expected.items() if not path.exists() or path.read_text(encoding="utf-8") != content]
    if args.check:
        if stale:
            print("command documentation is stale; run `uv run scripts/docs.py`")
            return 1
        print("command documentation is current")
    else:
        for path in stale:
            path.write_text(expected[path], encoding="utf-8")
        print("wrote command documentation")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
